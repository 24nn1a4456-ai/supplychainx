"""
engine_adapter.py — Bridge between the new API layer and Member 4's decision engine.

Invokes the REAL existing functions:
  create_disruption() → scenario_to_optimizer_inputs() → plan_recovery() → compute_kpis()

Never fabricates optimizer results or claims greedy is optimal.
"""
from __future__ import annotations

import json
import math
from typing import Any, Dict, List, Optional, Tuple

from backend.simulator.scenarios import SCENARIO_REGISTRY, load_scenario
from backend.simulator.simulator import (
    create_disruption,
    scenario_to_optimizer_inputs,
    list_available_scenarios,
)
from backend.optimizer import plan_recovery
from backend.optimizer.schemas import RecoveryPlan
from backend.evaluation.kpis import compute_kpis, KPIResult
from backend.evaluation.evaluator import APPROACH_C


class EngineAdapter:
    """
    Stateless adapter that invokes Member 4's decision engine.
    
    All method results come from the real engine — no values are fabricated.
    """

    @staticmethod
    def available_scenarios() -> List[str]:
        return list_available_scenarios()

    @staticmethod
    def run_scenario(
        scenario_name: str,
        delay_penalty_per_day: float = 5.0,
        budget_limit: float = float("inf"),
    ) -> Dict[str, Any]:
        """
        Execute the full engine pipeline for a named scenario.

        Returns a dict containing plan, KPIs, state, and solver metadata.
        """
        # Step 1: Create disruption (uses the real simulator)
        state = create_disruption(scenario_name)

        # Step 2: Convert to optimizer inputs
        demands, warehouses, suppliers, config = scenario_to_optimizer_inputs(
            state,
            budget_limit=budget_limit,
            delay_penalty_per_day=delay_penalty_per_day,
        )

        # Step 3: Run the real optimizer (CP-SAT or greedy fallback)
        plan = plan_recovery(demands, warehouses, suppliers, config)

        # Step 4: Compute KPIs from actual plan output
        kpi = compute_kpis(APPROACH_C, state, demands, plan)

        # Build serializable result
        plan_dict = plan.to_dict()
        kpi_dict = kpi.to_dict()

        # Serialize actions for storage
        actions_list = [a.to_dict() for a in plan.actions]
        fulfilled_map = dict(plan.fulfilled)

        return {
            "scenario_name": scenario_name,
            "scenario_id": state.scenario_id,
            "state": {
                "scenario_name": state.scenario_name,
                "events": [e.to_dict() for e in state.events],
                "orders": [{"component_id": o.component_id, "quantity": o.quantity,
                           "due_date_days": o.due_date_days, "priority": o.priority}
                          for o in state.orders],
                "total_demand": state.total_demand,
            },
            "plan": {
                "actions": actions_list,
                "solver_status": plan.solver_status.value,
                "solver_type": plan.solver_type,
                "total_cost": plan.total_cost,
                "procurement_cost": plan.total_procurement_cost,
                "delay_penalty": plan.total_delay_penalty,
                "is_feasible": not plan.is_infeasible,
                "is_infeasible": plan.is_infeasible,
                "fulfilled": fulfilled_map,
                "violated_constraints": list(plan.violated_constraints),
                "solver_wall_time_s": plan.solver_wall_time_seconds,
            },
            "kpis": kpi_dict,
            "warnings": _build_warnings(plan, kpi),
        }

    @staticmethod
    def compute_plan_kpis(scenario_name: str, plan: RecoveryPlan) -> Dict[str, Any]:
        """Recompute KPIs for a given plan (used by simulation)."""
        state = create_disruption(scenario_name)
        demands, _, _, _ = scenario_to_optimizer_inputs(state)
        kpi = compute_kpis(APPROACH_C, state, demands, plan)
        return kpi.to_dict()


def _build_warnings(plan: RecoveryPlan, kpi: KPIResult) -> List[str]:
    """Generate human-readable warnings about the plan."""
    warnings = []

    if plan.is_infeasible:
        warnings.append("INFEASIBLE: No feasible recovery plan found. Manual intervention required.")
        if plan.violated_constraints:
            for vc in plan.violated_constraints:
                warnings.append(f"  Constraint: {vc}")

    if plan.solver_type == "greedy_fallback":
        warnings.append(
            "FALLBACK: CP-SAT solver was unavailable or failed. "
            "Plan generated by greedy heuristic — NOT guaranteed optimal."
        )

    if kpi.fulfillment_rate_pct < 100.0:
        warnings.append(
            f"PARTIAL FULFILLMENT: Only {kpi.fulfillment_rate_pct:.1f}% of demand can be met."
        )

    if kpi.on_time_rate_pct < 100.0:
        warnings.append(
            f"DELIVERY DELAYS: {kpi.on_time_rate_pct:.1f}% of fulfilled units arrive on time."
        )

    return warnings
